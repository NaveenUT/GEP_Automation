// Builds LOCATORS_TODO.md from the page objects and components, so the checklist always matches the code.
// Every locator getter must be preceded by a "// Tosca: <module> > <control>   | <hint>" comment.
// Usage: npm run locators
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE_DIRS = ['src/components', 'src/pages'];

function listFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(full);
    return entry.name.endsWith('.ts') ? [full] : [];
  });
}

const escapeCell = (text) => text.replace(/\|/g, '\\|').trim();
const rows = [];

for (const file of SOURCE_DIRS.flatMap((dir) => listFiles(path.join(ROOT, dir)))) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const className = (lines.join('\n').match(/export class (\w+)/) || [])[1] || path.basename(file, '.ts');

  lines.forEach((line, index) => {
    const getter = line.match(/^\s+(?:get\s+)?(\w+)\(([^)]*)\): Locator \{/);
    if (!getter) return;

    const comment = (lines[index - 1] || '').match(/^\s*\/\/\s*(.*)$/);
    const [toscaPart, hint = ''] = comment ? comment[1].split(/\s+\|\s+/) : ['', ''];
    const tosca = toscaPart.replace(/^Tosca:\s*/, '');

    // Body = lines until the getter's closing brace at the same indent.
    const indent = line.match(/^\s*/)[0];
    const body = [];
    for (let i = index + 1; i < lines.length && lines[i] !== `${indent}}`; i++) body.push(lines[i].trim());
    const bodyText = body.join(' ');
    const isTodo = /this\.todo\(/.test(bodyText);
    const code = escapeCell(bodyText.replace(/^return\s+/, '').replace(/;$/, ''));
    // A code span that contains backticks (template strings) needs double-backtick delimiters.
    const locator = isTodo ? '–' : code.includes('`') ? `\`\` ${code} \`\`` : `\`${code}\``;

    const name = getter[2] ? `${getter[1]}(${getter[2].replace(/:\s*\w+/g, '')})` : getter[1];
    rows.push({ className, name, tosca: escapeCell(tosca || '–'), hint: escapeCell(hint || '–'), status: isTodo ? 'TODO' : 'Filled', locator });
  });
}

rows.sort((a, b) => a.className.localeCompare(b.className));
const todoCount = rows.filter((row) => row.status === 'TODO').length;

const output = [
  '# Locators',
  '',
  `Generated by \`npm run locators\` from \`src/components\` and \`src/pages\`. Do not edit by hand.`,
  '',
  `${rows.length} locators, ${rows.length - todoCount} filled, ${todoCount} still TODO (a \`this.todo(...)\` placeholder that fails the test when it is reached).`,
  '',
  '| Class | Getter | Tosca module > control | Note | Status | Locator |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.className} | ${r.name} | ${r.tosca} | ${r.hint} | ${r.status} | ${r.locator} |`),
  '',
].join('\n');

fs.writeFileSync(path.join(ROOT, 'LOCATORS_TODO.md'), output);
console.log(`LOCATORS_TODO.md: ${rows.length} locators, ${todoCount} TODO`);
